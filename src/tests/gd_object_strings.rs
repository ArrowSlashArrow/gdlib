/// Parses every object in the GD-saved test levels and checks that gdlib writes it back as an
/// equivalent object string. On failure, prints how many objects differ per key, with one example each.
#[test]
fn every_gd_object_reserialises_to_an_equivalent_string() {
    // key -> (number of objects, first example)
    let mut failures: BTreeMap<String, (usize, String)> = BTreeMap::new();
    let mut checked = 0;
    for path in GD_SAVED_LEVELS {
        let raw = GDLevel::from_gmd(path)
            .unwrap_or_else(|e| panic!("{path}: {e}"))
            .get_raw_decrypted_data()
            .unwrap_or_else(|| panic!("{path}: no level data"));
        // the first `;`-separated section is the level header, not an object
        for gd in raw.split(';').skip(1).filter(|s| !s.is_empty()) {
            let gd = format!("{gd};");
            let ours = GDObject::parse_str(&gd).serialise_to_string();
            for (key, msg) in object_string_diffs(&ours, &gd, &[]) {
                let entry = failures.entry(key).or_default();
                if entry.0 == 0 {
                    entry.1 = format!("{msg}\n    {path}\n    gdlib: {ours}\n    GD:    {gd}");
                }
                entry.0 += 1;
            }
            checked += 1;
        }
    }
    assert!(checked > 0, "no objects were checked");
    assert!(
        failures.is_empty(),
        "{checked} objects checked. Differences per key:\n{}",
        failures
            .into_iter()
            .map(|(key, (n, example))| format!("  key {key}: {n} objects, e.g.\n    {example}"))
            .collect::<Vec<_>>()
            .join("\n")
    );
}
