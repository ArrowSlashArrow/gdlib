//! Tests that compare object strings written by gdlib against object strings saved by Geometry Dash itself.
//!
//! Every sample string in this file was copied from a level that was saved by the game (the levels in
//! `test_gmds/`). The tests build the same object with gdlib, serialise it and check that the output
//! describes the same object as the string GD wrote.
//!
//! Object strings are compared as key/value maps, not as raw text, because:
//! * GD and gdlib write properties in a different order. GD doesn't care about the order.
//! * GD leaves out most properties that have their default value (`0`), while gdlib sometimes writes
//!   them anyway. A property that only one side has therefore matches if its value is zero.
//! * GD writes whole floats without a decimal point (`2`), gdlib writes `2.0`. Numbers are compared by
//!   value, at f32 precision (which is what GD stores).
//! * Group lists (`57`, `274`) are compared as sets, since GD doesn't sort them.
//!
//! Properties in [`GD_DERIVED_PROPERTIES`] are skipped. GD works them out from the object itself, so
//! they are not part of the object's data.
use std::collections::{BTreeMap, BTreeSet};

use crate::cclocallevels::{
    gdlevel::GDLevel,
    gdobj::{
        GDObject,
        constructors::TextObject,
        constructors::triggers::{
            AlphaTrigger, ColourTrigger, CounterLabel, GravityTrigger, ItemEditTrigger,
            MoveTrigger, PulseTrigger, ScaleTrigger, SpawnTrigger, ToggleTrigger,
        },
        meta::{GDObjAttributes, GDObjConfig},
        structs::{
            Colour, ColourChannel, DefaultMove, Easing, Item, ItemAlign, MoveEasing, MoveMode, Op,
            PulseMode, PulseTarget, RoundMode, ScaleConfig, SignMode, ZLayer,
        },
    },
};

/// Properties that GD writes on (almost) every object, but that it works out from the object itself:
/// * `155`: base colour cached index
/// * `156`: detail colour cached index
/// * `36`: "is interactable". GD writes `36,1` on every trigger, pad, orb and portal no matter how it is
///   set up, so it says nothing about the object. gdlib's constructors don't write it.
const GD_DERIVED_PROPERTIES: &[&str] = &["155", "156", "36"];

/// Properties whose value is a `.`-separated list where the order doesn't matter.
const UNORDERED_LIST_PROPERTIES: &[&str] = &["57", "274"];

/// Levels in `test_gmds/` that were saved by GD (not generated by gdlib).
const GD_SAVED_LEVELS: &[&str] = &[
    "test_gmds/level.gmd",
    "test_gmds/empty test level.gmd",
    "test_gmds/advrand test.gmd",
    "test_gmds/Chompstep.gmd",
    "test_gmds/All Object IDs.gmd",
    "test_gmds/big.gmd",
];

/// Splits an object string into a key -> value map. Also returns the keys that appear more than once.
/// GD itself sometimes writes a key twice (e.g. `512` on object 2917), in which case the last value wins.
fn kv_map(s: &str) -> (BTreeMap<String, String>, Vec<String>) {
    let tokens: Vec<&str> = s.trim_end_matches(';').split(',').collect();
    assert!(
        tokens.len() % 2 == 0,
        "object string has an odd number of fields: {s}"
    );
    let mut map = BTreeMap::new();
    let mut duplicates = vec![];
    for pair in tokens.chunks(2) {
        if map
            .insert(pair[0].to_string(), pair[1].to_string())
            .is_some()
        {
            duplicates.push(pair[0].to_string());
        }
    }
    (map, duplicates)
}

/// Whether two values of `key` mean the same thing to GD.
fn values_match(key: &str, a: &str, b: &str) -> bool {
    if a == b {
        return true;
    }
    if UNORDERED_LIST_PROPERTIES.contains(&key) {
        fn sorted(s: &str) -> Vec<&str> {
            let mut v: Vec<&str> = s.split('.').collect();
            v.sort_unstable();
            v
        }
        return sorted(a) == sorted(b);
    }
    // GD stores numbers as f32 and writes them with 6 significant digits (`0.880245`), while gdlib may
    // write more (`0.88024497`). Both read back as the same f32, so compare at that precision.
    match (a.parse::<f32>(), b.parse::<f32>()) {
        (Ok(x), Ok(y)) => x == y,
        _ => false,
    }
}

/// Whether a property that is only written by one side is fine to leave out (GD omits zeros and empty lists).
fn is_omittable(value: &str) -> bool {
    value.is_empty() || value.parse::<f64>().is_ok_and(|v| v == 0.0)
}

/// Returns every difference between a gdlib object string and a GD object string as `(key, message)`
/// pairs, or an empty list if they match. Keys in `allowed` are not compared.
fn object_string_diffs(gdlib: &str, gd: &str, allowed: &[&str]) -> Vec<(String, String)> {
    let mut diffs = vec![];
    let mut push = |key: &str, msg: String| diffs.push((key.to_string(), msg));
    if !gdlib.ends_with(';') {
        push("format", "gdlib string doesn't end with `;`".into());
    }
    let gd_id = gd.split(',').nth(1).unwrap_or_default();
    if !gdlib.starts_with(&format!("1,{gd_id},")) {
        push(
            "format",
            format!("gdlib string doesn't start with `1,{gd_id},`"),
        );
    }

    let ((ours, duplicates), (theirs, _)) = (kv_map(gdlib), kv_map(gd));
    for key in duplicates {
        push(&key, format!("key {key}: gdlib wrote it more than once"));
    }
    let keys = ours
        .keys()
        .chain(theirs.keys())
        .map(String::as_str)
        .filter(|k| !GD_DERIVED_PROPERTIES.contains(k) && !allowed.contains(k))
        .collect::<BTreeSet<_>>();
    for key in keys {
        match (ours.get(key), theirs.get(key)) {
            (Some(a), Some(b)) if !values_match(key, a, b) => {
                push(key, format!("key {key}: gdlib wrote `{a}`, GD wrote `{b}`"))
            }
            (Some(a), None) if !is_omittable(a) => {
                push(key, format!("key {key}: gdlib wrote `{a}`, GD left it out"))
            }
            (None, Some(b)) if !is_omittable(b) => {
                push(key, format!("key {key}: gdlib left it out, GD wrote `{b}`"))
            }
            _ => {}
        }
    }
    diffs
}

/// Asserts that `obj` serialises to an object string equivalent to `gd`, a string saved by GD.
#[track_caller]
fn assert_matches_gd(obj: &GDObject, gd: &str) {
    assert_matches_gd_except(obj, gd, &[]);
}

/// Like [`assert_matches_gd`], but doesn't compare the keys in `allowed`. Say why next to every use.
#[track_caller]
fn assert_matches_gd_except(obj: &GDObject, gd: &str, allowed: &[&str]) {
    let ours = obj.serialise_to_string();
    let diffs = object_string_diffs(&ours, gd, allowed);
    assert!(
        diffs.is_empty(),
        "\n{}\ngdlib: {ours}\nGD:    {gd}",
        diffs
            .into_iter()
            .map(|(_, m)| m)
            .collect::<Vec<_>>()
            .join("\n")
    );
}

// ---------------- comparator self-checks ----------------

#[test]
fn comparator_ignores_order_number_format_and_derived_properties() {
    let diffs = object_string_diffs(
        "1,1,2,15.0,3,0,57,2.1;",
        "1,1,3,0,57,1.2,2,15,155,4,36,1;",
        &[],
    );
    assert!(diffs.is_empty(), "{diffs:?}");
}

#[test]
fn comparator_treats_missing_zero_as_default() {
    assert!(object_string_diffs("1,901,2,0,3,0,397,0,442,;", "1,901,2,0,3,0;", &[]).is_empty());
    assert!(!object_string_diffs("1,901,2,0,3,0,397,1;", "1,901,2,0,3,0;", &[]).is_empty());
}

#[test]
fn comparator_catches_wrong_values_ids_and_format() {
    assert!(!object_string_diffs("1,1,2,0,3,0,21,3;", "1,1,2,0,3,0,21,4;", &[]).is_empty());
    assert!(!object_string_diffs("1,2,2,0,3,0;", "1,1,2,0,3,0;", &[]).is_empty());
    assert!(!object_string_diffs("1,1,2,0,3,0", "1,1,2,0,3,0;", &[]).is_empty());
    assert!(!object_string_diffs("1,1,2,0,3,0,21,3,21,3;", "1,1,2,0,3,0,21,3;", &[]).is_empty());
}

#[test]
fn comparator_allowed_keys_are_skipped() {
    assert!(object_string_diffs("1,901,2,0,3,0,393,1;", "1,901,2,0,3,0;", &["393"]).is_empty());
}

