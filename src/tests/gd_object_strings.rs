/// GD only writes the base colour (`21`), detail colour (`22`) and Z layer (`24`) when they differ from
/// *that object's* default, which isn't the same for every object. So when GD writes one of them,
/// gdlib must write it too, even if it equals [`GDObjConfig`]'s default. Leaving it out makes GD fall
/// back to the object's own default, which changes the object.
#[test]
fn explicit_colour_and_z_layer_are_kept() {
    // Chompstep.gmd: decoration explicitly set to the object colour channel (1004)
    let cfg = GDObjConfig::new()
        .with_pos(13605.0, 345.0)
        .with_groups([27i16])
        .with_base_colour(ColourChannel::Object);
    assert_matches_gd(
        &GDObject::new(1148, &cfg, vec![]),
        "1,1148,2,13605,3,345,57,27,155,3,21,1004;",
    );

    // Chompstep.gmd: toggle trigger explicitly on Z layer T1 (5)
    let cfg = GDObjConfig::new()
        .with_pos(-45.0, 1155.0)
        .with_z_layer(ZLayer::T1)
        .with_z_order(2)
        .with_attributes(GDObjAttributes::high_detail, true);
    let toggle = ToggleTrigger {
        target_group: 119,
        activate_group: false,
    };
    let obj = GDObject::from_config(&cfg, toggle);
    assert_matches_gd(
        &obj,
        "1,1049,2,-45,3,1155,103,1,155,1,25,2,24,5,36,1,51,119;",
    );
}

